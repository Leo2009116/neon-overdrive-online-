let _auxSkillInterval = null;
function ensureAuxSkillsLoop() {
  if (_auxSkillInterval) return;
  _auxSkillInterval = setInterval(() => {
    if (typeof state === "undefined" || state !== "PLAY" || !player) return;
    const effDmg = typeof getEffectivePlayerDmg === "function" ? getEffectivePlayerDmg() : player.dmg;

    if (player.teslaLvl > 0 && Array.isArray(enemies) && enemies.length > 0) {
      player.teslaTick = (player.teslaTick || 0) + 1;
      if (player.teslaTick >= 6) {
        player.teslaTick = 0;
        let hitCount = 0;
        const maxTargets = 1 + player.teslaLvl;
        for (let i = enemies.length - 1; i >= 0 && hitCount < maxTargets; i--) {
          const e = enemies[i];
          if (!e || e.hp <= 0) continue;
          if (Math.hypot(e.x - player.x, e.y - player.y) <= 280) {
            const tDmg = effDmg * (0.65 + player.teslaLvl * 0.25);
            e.hp -= tDmg;
            hitCount++;
            if (typeof shockwaves !== "undefined") {
              shockwaves.push({ x: e.x, y: e.y, r: 4, maxR: 38, color: "#00f3ff", alpha: 0.85 });
            }
            if (typeof addFloatText === "function") addFloatText(e.x, e.y - 14, `⚡${Math.round(tDmg)}`, "#00f3ff");
            if (e.hp <= 0 && typeof handleEnemyDeath === "function") handleEnemyDeath(e, i);
          }
        }
      }
    }

    if (player.missileLvl > 0 && typeof findNearestEnemy === "function" && Array.isArray(bullets)) {
      player.missileTick = (player.missileTick || 0) + 1;
      if (player.missileTick >= 7) {
        player.missileTick = 0;
        const target = findNearestEnemy(player.x, player.y, 750);
        if (target) {
          for (let m = 0; m < player.missileLvl; m++) {
            const spread = (m - (player.missileLvl - 1) / 2) * 0.22;
            const ang = Math.atan2(target.y - player.y, target.x - player.x) + spread;
            bullets.push({
              x: player.x, y: player.y,
              vx: Math.cos(ang) * 13, vy: Math.sin(ang) * 13,
              baseAngle: ang, speed: 13, r: 7, dmg: effDmg * 1.45,
              pierce: 1, ricochet: 1, color: "#ff007f",
              shape: "DIAMOND", traj: "STRAIGHT", tick: 0
            });
          }
        }
      }
    }
  }, 200);
}

